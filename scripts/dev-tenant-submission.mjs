#!/usr/bin/env node
// Creates a tenant form submission in the LOCAL dev environment, so the admin UI can be tried
// without the public form. Goes through the real API like a guest would: the admin creates an
// invitation, the guest opens it, uploads a picture and a PDF, saves a draft and submits in Swedish.
// Only the Google sign-in is simulated, by writing the binding to the local D1 directly.
//
// Needs `npm run dev` running (local D1 with migrations and `npm run db:seed:local`).
// Refuses any API that is not on localhost.
//
// Usage:
//   npm run dev:tenant-submission                 submitted form
//   npm run dev:tenant-submission -- --no-submit  opened and signed in, draft saved, not submitted

import { exec } from 'node:child_process'
import { createHmac, randomUUID } from 'node:crypto'
import { readFileSync, rmSync, writeFileSync } from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { promisify } from 'node:util'
import { deflateSync } from 'node:zlib'

const API_BASE = process.env.PORTAL_API_LOCAL_URL ?? 'http://localhost:8787'
const ADMIN_UI_BASE = 'http://localhost:5173'
const OFFER_ID = 'offer_001'
const SUBMIT = !process.argv.includes('--no-submit')
const DAY_MS = 86_400_000
const execAsync = promisify(exec)

main().catch((error) => {
	const cause = error.cause instanceof Error ? ` (${error.cause.message})` : ''
	console.error(`\n✗ ${error.message}${cause}`)
	process.exit(1)
})

async function main() {
	const apiHost = new URL(API_BASE).hostname
	if (apiHost !== 'localhost' && apiHost !== '127.0.0.1') {
		throw new Error(`Refusing to run against ${API_BASE}: this script is for the local dev API only.`)
	}

	const devVars = readDevVars()
	await checkApiIsRunning()

	console.log('1. Admin creates an invitation')
	const adminCookie = `session=${signToken({ typ: 'admin', email: readAdminEmail(), exp: inSeconds(3600) }, devVars.SESSION_SECRET)}`
	const created = await api('POST', '/api/admin/tenant-forms/invitations', {
		headers: { Cookie: adminCookie },
		json: { displayName: 'Åsa Exempel (dev)', offerId: OFFER_ID, language: 'sv', validDays: 5 },
	})
	const invitationId = created.invitation.id
	const invitationToken = created.url.split('/').pop()

	console.log('2. Guest opens the link')
	await api('POST', '/api/tenant-forms/invitations/resolve', { json: { token: invitationToken } })

	console.log('3. Guest signs in with Google (simulated in the local D1)')
	const googleSubject = `dev-google-subject-${invitationId.slice(0, 8)}`
	await simulateGoogleSignIn(invitationId, googleSubject)
	const bearer = {
		Authorization: `Bearer ${signToken({ typ: 'tenant_form', inv: invitationId, sub: googleSubject, exp: inSeconds(7200) }, devVars.TENANT_FORM_SECRET)}`,
	}

	console.log('4. Guest uploads a picture and a PDF')
	const picture = await uploadFile(bearer, 'passport Åsa.png', 'image/png', createTestPng(800, 500))
	const pdf = await uploadFile(bearer, 'id-card-scan.pdf', 'application/pdf', createTestPdf('Test ID card scan - dev data'))

	console.log('5. Guest saves a draft')
	await api('PUT', '/api/tenant-forms/draft', { headers: bearer, json: { values: { first_name: 'Åsa', phone: '+46 70' } } })

	if (!SUBMIT) {
		console.log(`\n✓ Invitation ${invitationId} is opened and signed in, with a draft and two files.`)
		console.log(`  Admin UI: ${ADMIN_UI_BASE}/tenant-forms`)
		return
	}

	console.log('6. Guest submits the form')
	const submitted = await api('POST', '/api/tenant-forms/submit', {
		headers: bearer,
		json: { values: swedishSubmission([picture.id, pdf.id]) },
	})

	console.log(`\n✓ Submission ${submitted.submissionId}`)
	console.log(`  Admin UI: ${ADMIN_UI_BASE}/tenant-forms/submissions/${submitted.submissionId}`)
}

// --- Local environment ---

function readDevVars() {
	const vars = {}
	for (const line of readFileSync('.dev.vars', 'utf8').split(/\r?\n/)) {
		const match = line.match(/^([A-Z0-9_]+)=(.*)$/)
		if (match) vars[match[1]] = match[2].trim()
	}
	for (const name of ['SESSION_SECRET', 'TENANT_FORM_SECRET']) {
		if (!vars[name]) throw new Error(`${name} is missing in .dev.vars (see .dev.vars.example).`)
	}
	return vars
}

function readAdminEmail() {
	const source = readFileSync('src/utils/adminAllowlist.ts', 'utf8')
	const match = source.match(/new Set\(\[\s*'([^']+)'/)
	if (!match) throw new Error('Could not read the admin email from src/utils/adminAllowlist.ts.')
	return match[1]
}

async function checkApiIsRunning() {
	try {
		const response = await fetch(`${API_BASE}/api/health`)
		if (response.ok) return
	} catch {
		// Reported below.
	}
	throw new Error(`The local API is not answering at ${API_BASE}. Start it first with: npm run dev`)
}

async function simulateGoogleSignIn(invitationId, googleSubject) {
	const now = new Date().toISOString().replace(/\.\d{3}Z$/, 'Z')
	// All values are generated by this script, so inlining them is safe.
	await runLocalSql(`
		UPDATE form_invitations
		SET google_subject = '${googleSubject}', google_email = 'dev.guest@example.com',
		    authenticated_at = '${now}', updated_at = CURRENT_TIMESTAMP
		WHERE id = '${invitationId}';
		INSERT INTO form_events (id, invitation_id, event_type, actor_type, actor_ref)
		VALUES ('${randomUUID()}', '${invitationId}', 'tenant_authenticated', 'tenant', '${googleSubject}');
	`)
}

// Asynchronous on purpose: blocking the event loop lets the server close the kept-alive
// connection unnoticed, and the next POST then fails with ECONNRESET.
async function runLocalSql(sql) {
	const file = path.join(os.tmpdir(), `tenant-dev-${randomUUID()}.sql`)
	writeFileSync(file, sql)
	try {
		// One command string: npx is a .cmd file on Windows and needs a shell.
		await execAsync(`npx wrangler d1 execute portal-db --local --persist-to .wrangler/local-state --file "${file}"`)
	} catch (error) {
		throw new Error(`wrangler d1 execute failed:\n${error.stderr || error.message}`)
	} finally {
		rmSync(file, { force: true })
	}
}

// --- API ---

async function api(method, apiPath, { headers = {}, json } = {}) {
	const response = await fetch(`${API_BASE}${apiPath}`, {
		method,
		headers: json === undefined ? headers : { ...headers, 'Content-Type': 'application/json' },
		body: json === undefined ? undefined : JSON.stringify(json),
	})
	const body = await response.json().catch(() => null)
	if (!response.ok) {
		const hint = apiPath.endsWith('/invitations') && response.status === 400 ? ' (is the dev seed loaded? npm run db:seed:local)' : ''
		throw new Error(`${method} ${apiPath} → ${response.status} ${JSON.stringify(body)}${hint}`)
	}
	return body
}

async function uploadFile(headers, fileName, contentType, bytes) {
	const response = await fetch(`${API_BASE}/api/tenant-forms/files`, {
		method: 'POST',
		headers: { ...headers, 'Content-Type': contentType, 'X-Field-Key': 'id_documents', 'X-File-Name': encodeURIComponent(fileName) },
		body: bytes,
	})
	const body = await response.json().catch(() => null)
	if (!response.ok) throw new Error(`Upload of ${fileName} → ${response.status} ${JSON.stringify(body)}`)
	return body.file
}

// --- Tokens (same formats as src/utils/signedToken.ts and src/utils/tokens.ts) ---

function signToken(payload, secret) {
	const payloadB64 = Buffer.from(JSON.stringify(payload)).toString('base64url')
	return `${payloadB64}.${createHmac('sha256', secret).update(payloadB64).digest('base64url')}`
}

function inSeconds(seconds) {
	return Math.floor(Date.now() / 1000) + seconds
}


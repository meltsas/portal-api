/** A real, viewable PNG with stripes, built without dependencies. */
function createTestPng(width, height) {
	const rows = []
	for (let y = 0; y < height; y++) {
		const row = Buffer.alloc(1 + width * 3)
		for (let x = 0; x < width; x++) {
			const stripe = Math.floor((x + y) / 50) % 2 === 0
			row.set(stripe ? [0x03, 0xbf, 0xd7] : [0xf2, 0xfe, 0xff], 1 + x * 3)
		}
		rows.push(row)
	}
	const header = Buffer.alloc(13)
	header.writeUInt32BE(width, 0)
	header.writeUInt32BE(height, 4)
	header.set([8, 2, 0, 0, 0], 8) // 8-bit RGB, no interlace
	return Buffer.concat([
		Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
		pngChunk('IHDR', header),
		pngChunk('IDAT', deflateSync(Buffer.concat(rows))),
		pngChunk('IEND', Buffer.alloc(0)),
	])
}

function pngChunk(type, data) {
	const length = Buffer.alloc(4)
	length.writeUInt32BE(data.length)
	const typeAndData = Buffer.concat([Buffer.from(type, 'ascii'), data])
	const crc = Buffer.alloc(4)
	crc.writeUInt32BE(crc32(typeAndData))
	return Buffer.concat([length, typeAndData, crc])
}

function crc32(bytes) {
	let crc = 0xffffffff
	for (const byte of bytes) {
		crc ^= byte
		for (let bit = 0; bit < 8; bit++) crc = crc & 1 ? (crc >>> 1) ^ 0xedb88320 : crc >>> 1
	}
	return (crc ^ 0xffffffff) >>> 0
}

/** A one-page PDF with a line of ASCII text. */
function createTestPdf(text) {
	const content = `BT /F1 24 Tf 72 760 Td (${text}) Tj ET`
	const objects = [
		'<< /Type /Catalog /Pages 2 0 R >>',
		'<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
		'<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Contents 4 0 R /Resources << /Font << /F1 5 0 R >> >> >>',
		`<< /Length ${content.length} >>\nstream\n${content}\nendstream`,
		'<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',
	]
	let pdf = '%PDF-1.4\n'
	const offsets = []
	objects.forEach((object, index) => {
		offsets.push(pdf.length)
		pdf += `${index + 1} 0 obj\n${object}\nendobj\n`
	})
	const xrefOffset = pdf.length
	pdf += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`
	pdf += offsets.map((offset) => `${String(offset).padStart(10, '0')} 00000 n \n`).join('')
	pdf += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xrefOffset}\n%%EOF\n`
	return Buffer.from(pdf, 'latin1')
}
